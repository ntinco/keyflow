class CatalogError(RuntimeError):
    pass


def _row_to_entry(row: tuple[object, ...]) -> dict[str, object]:
    entry = dict(zip(DB_COLUMNS, row))
    try:
        entry["platform"] = json.loads(entry["platform"])
    except (TypeError, json.JSONDecodeError) as exc:
        raise CatalogError(f"Invalid JSON fields for hotkey {entry.get('id')}: {exc}") from exc
    entry["active"] = bool(entry["active"])
    return entry


def create_db() -> None:
    if DB_PATH.exists():
        raise CatalogError(f"Refusing to replace existing human catalog: {DB_PATH}")
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(DB_PATH) as connection:
        connection.executescript(DB_SCHEMA)
    print(f"Created empty catalog: {DB_PATH}")


def migrate_hotkeys_schema() -> None:
    if not DB_PATH.exists():
        raise CatalogError(f"Human catalog not found: {DB_PATH}")

    with sqlite3.connect(DB_PATH) as connection:
        columns = [row[1] for row in connection.execute("PRAGMA table_info(hotkeys)")]
        if columns == DB_COLUMNS:
            print("Hotkey schema is already current.")
            return
        if columns != LEGACY_HOTKEY_COLUMNS:
            raise CatalogError(
                "Unexpected legacy hotkeys schema. Expected columns: "
                + ", ".join(LEGACY_HOTKEY_COLUMNS)
            )

        connection.execute("BEGIN IMMEDIATE")
        old_count = connection.execute("SELECT COUNT(*) FROM hotkeys").fetchone()[0]
        old_ids = {row[0] for row in connection.execute("SELECT id FROM hotkeys")}
        connection.execute("ALTER TABLE hotkeys RENAME TO hotkeys_legacy")
        connection.execute(HOTKEYS_TABLE_SCHEMA)
        connection.execute(
            """
            INSERT INTO hotkeys (
                sort_order, id, file, type, key, trigger, options,
                windows_context, context_label, action, label,
                platform, active, portability
            )
            SELECT
                sort_order, id, file, type, key, trigger, options,
                CASE
                    WHEN COALESCE(context_fn, '') != '' THEN context_fn
                    WHEN COALESCE(context, '') != '' THEN 'winactive(' || context || ')'
                    ELSE NULL
                END,
                context_label, action, label, platform, active, portability
            FROM hotkeys_legacy
            """
        )
        new_count = connection.execute("SELECT COUNT(*) FROM hotkeys").fetchone()[0]
        new_ids = {row[0] for row in connection.execute("SELECT id FROM hotkeys")}
        invalid_contexts = connection.execute(
            "SELECT id FROM hotkeys WHERE windows_context LIKE '#hotif%'"
        ).fetchall()
        if new_count != old_count or new_ids != old_ids or invalid_contexts:
            raise CatalogError("Hotkey schema migration failed its data-preservation checks.")
        connection.execute("DROP TABLE hotkeys_legacy")

    print(f"Migrated {old_count} hotkeys to the current schema.")


def migrate_hotstring_profiles() -> None:
    profiles = [
        ("autocorrect", "replace", "global", ["windows", "macos"]),
        ("quick-snippets", "replace", "global", ["windows", "macos"]),
        ("sap-transaction-shortcuts", "sap-command", "sap-gui-session", ["windows", "macos"]),
        ("sap-transaction-catalog", "sap-command", "sap-gui-session", ["windows", "macos"]),
        ("ymt-commands", "sap-command", "sap-gui-session", ["windows", "macos"]),
    ]
    with sqlite3.connect(DB_PATH) as connection:
        connection.executescript(DB_SCHEMA)
        existing = connection.execute("SELECT COUNT(*) FROM hotstring_profiles").fetchone()[0]
        if existing:
            raise CatalogError("Refusing to overwrite existing hotstring profile catalog.")
        for profile_order, (profile_id, mode, context_label, platform) in enumerate(profiles):
            source_path = WINDOWS_DATA_DIR / f"{profile_id}.json"
            payload = json.loads(source_path.read_text(encoding="utf-8"))
            items = payload.get("items")
            if not isinstance(items, list) or not items:
                raise CatalogError(f"{source_path}: expected non-empty items[]")
            connection.execute(
                "INSERT INTO hotstring_profiles "
                "(sort_order, id, mode, context_label, platform, active) VALUES (?, ?, ?, ?, ?, 1)",
                (profile_order, profile_id, mode, context_label, json.dumps(platform)),
            )
            for entry_order, item in enumerate(items):
                trigger = item.get("trigger")
                value = item.get("value")
                if not isinstance(trigger, str) or not trigger or not isinstance(value, str) or not value:
                    raise CatalogError(f"{source_path}: entry {entry_order} requires trigger and value")
                connection.execute(
                    "INSERT INTO hotstring_entries "
                    "(profile_id, sort_order, trigger, value, immediate) VALUES (?, ?, ?, ?, ?)",
                    (profile_id, entry_order, trigger, value, int(bool(item.get("immediate")))),
                )
    print(f"Migrated {len(profiles)} hotstring profiles into {DB_PATH}.")


def load_hotstring_profiles() -> list[dict[str, object]]:
    if not DB_PATH.exists():
        raise CatalogError(f"Human catalog not found: {DB_PATH}")
    connection = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    try:
        profiles = connection.execute(
            "SELECT sort_order, id, mode, context_label, platform, active "
            "FROM hotstring_profiles ORDER BY sort_order, id"
        ).fetchall()
        entries = connection.execute(
            "SELECT profile_id, sort_order, trigger, value, immediate "
            "FROM hotstring_entries ORDER BY profile_id, sort_order, trigger"
        ).fetchall()
    finally:
        connection.close()

    by_profile: dict[str, list[dict[str, object]]] = defaultdict(list)
    for profile_id, sort_order, trigger, value, immediate in entries:
        if immediate not in {0, 1}:
            raise CatalogError(
                f"{profile_id}:{trigger}: immediate must be 0 or 1"
            )
        by_profile[str(profile_id)].append({
            "sort_order": sort_order,
            "trigger": trigger,
            "value": value,
            "immediate": bool(immediate),
        })

    result: list[dict[str, object]] = []
    for sort_order, profile_id, mode, context_label, platform, active in profiles:
        try:
            platforms = json.loads(platform)
        except (TypeError, json.JSONDecodeError) as exc:
            raise CatalogError(f"Invalid platform JSON for hotstring profile {profile_id}: {exc}") from exc
        if mode not in {"replace", "sap-command"}:
            raise CatalogError(f"{profile_id}: mode must be replace or sap-command")
        if not isinstance(platforms, list) or not platforms:
            raise CatalogError(f"{profile_id}: platform must be a non-empty JSON array")
        profile_entries = by_profile[str(profile_id)]
        if not profile_entries:
            raise CatalogError(f"{profile_id}: profile must contain at least one entry")
        result.append({
            "sort_order": sort_order,
            "id": profile_id,
            "mode": mode,
            "context_label": context_label,
            "platform": platforms,
            "active": bool(active),
            "entries": profile_entries,
        })
    return result


def load_db() -> list[dict[str, object]]:
    if not DB_PATH.exists():
        raise CatalogError(f"Human catalog not found: {DB_PATH}")
    connection = sqlite3.connect(f"file:{DB_PATH}?mode=ro", uri=True)
    try:
        columns = [row[1] for row in connection.execute("PRAGMA table_info(hotkeys)")]
        if columns != DB_COLUMNS:
            raise CatalogError(f"Unexpected hotkeys schema. Expected columns: {', '.join(DB_COLUMNS)}")
        rows = connection.execute("SELECT * FROM hotkeys ORDER BY sort_order, id").fetchall()
    finally:
        connection.close()
    entries = [_row_to_entry(row) for row in rows]
    validate_entries(entries)
    return entries


def _sap_tcode(entry: dict[str, object]) -> str | None:
    action = str(entry["action"])
    if not action.startswith(SAP_TCODE_ACTION_PREFIX):
        return None
    return action.removeprefix(SAP_TCODE_ACTION_PREFIX)


# Backspace sent by a hotstring action on top of AHK's automatic trigger erase.
HOTSTRING_BACKSPACE_RE = re.compile(r"\{\s*(?:bs|backspace)\b", re.IGNORECASE)


def validate_entries(entries: list[dict[str, object]]) -> None:
    issues: list[str] = []
    seen_ids: set[str] = set()
    seen_orders: set[int] = set()
    for entry in entries:
        entry_id = str(entry.get("id") or "<missing-id>")
        if not re.fullmatch(r"[a-z][a-z0-9_]*", str(entry.get("id") or "")):
            issues.append(f"{entry_id}: id must be lower_snake_case")
        sort_order = entry.get("sort_order")
        if entry_id in seen_ids:
            issues.append(f"duplicate id: {entry_id}")
        seen_ids.add(entry_id)
        if not isinstance(sort_order, int) or sort_order in seen_orders:
            issues.append(f"{entry_id}: sort_order must be a unique integer")
        if isinstance(sort_order, int):
            seen_orders.add(sort_order)

        file_key = str(entry.get("file") or "")
        if not FILE_KEY_RE.fullmatch(file_key) or ".." in file_key:
            issues.append(f"{entry_id}: invalid file key {file_key!r}")
        entry_type = entry.get("type")
        if entry_type not in {"hotkey", "hotstring"}:
            issues.append(f"{entry_id}: type must be hotkey or hotstring")
        if entry_type == "hotkey" and not entry.get("key"):
            issues.append(f"{entry_id}: hotkey requires key")
        if entry_type == "hotstring" and (not entry.get("trigger") or not entry.get("options")):
            issues.append(f"{entry_id}: hotstring requires trigger and options")
        windows_context = str(entry.get("windows_context") or "").strip()
        if windows_context.startswith("#hotif"):
            issues.append(f"{entry_id}: windows_context must be an expression without #hotif")
        platforms = entry.get("platform")
        if not isinstance(platforms, list) or not platforms:
            issues.append(f"{entry_id}: platform must be a non-empty JSON array")
        elif any(platform not in {"windows", "macos"} for platform in platforms):
            issues.append(f"{entry_id}: platform values must be windows or macos")
        if entry.get("portability") not in {"windows-only", "portable-intent"}:
            issues.append(f"{entry_id}: portability must be windows-only or portable-intent")
        action = str(entry.get("action") or "").strip()
        if not action or not str(entry.get("label") or "").strip():
            issues.append(f"{entry_id}: action and label are required")
        options = str(entry.get("options") or "").lower()
        if entry_type == "hotstring" and "b0" not in options and HOTSTRING_BACKSPACE_RE.search(action):
            issues.append(
                f"{entry_id}: hotstring already erases its trigger; sending backspace deletes user text "
                "(use option b0 to erase manually)"
            )
        tcode = _sap_tcode(entry)
        if tcode is not None and (
            entry_type != "hotkey" or not SAP_TCODE_RE.fullmatch(tcode)
        ):
            issues.append(
                f"{entry_id}: sap-tcode action requires a hotkey and a valid transaction code"
            )
        if tcode is not None and (
            entry.get("portability") != "portable-intent"
            or set(platforms if isinstance(platforms, list) else []) != {"windows", "macos"}
        ):
            issues.append(
                f"{entry_id}: sap-tcode action requires portable-intent on windows and macos"
            )
    if issues:
        raise CatalogError("Catalog validation failed:\n- " + "\n- ".join(issues))


# AutoHotkey's default EndChars (keyflow never overrides them); mirrored by
# END_CHARS in platforms/macos/hammerspoon/hotstrings.lua.
HOTSTRING_END_CHARS = set("-()[]{}':;\"/\\,.?! \t\r\n")


def _active_hotstring_triggers(
    entries: list[dict[str, object]],
    profiles: list[dict[str, object]],
) -> list[dict[str, object]]:
    triggers: list[dict[str, object]] = []
    for entry in entries:
        if entry["type"] == "hotstring" and entry["active"]:
            triggers.append({
                "trigger": str(entry["trigger"]),
                "immediate": "*" in str(entry["options"] or ""),
                "context": str(entry["context_label"] or "global"),
                "source": f"hotkeys:{entry['id']}",
            })
    for profile in profiles:
        if not profile["active"]:
            continue
        for item in profile["entries"]:
            triggers.append({
                "trigger": str(item["trigger"]),
                # sap-command profiles always wait for an ending character.
                "immediate": bool(item["immediate"]) and profile["mode"] != "sap-command",
                "context": str(profile["context_label"]),
                "source": f"{profile['id']}:{item['trigger']}",
            })
    return triggers


def find_hotstring_conflicts(
    entries: list[dict[str, object]],
    profiles: list[dict[str, object]],
) -> list[str]:
    """Report triggers that can never fire or fire ambiguously.

    Comparison is case-insensitive because Windows hotstrings are.
    """
    triggers = _active_hotstring_triggers(entries, profiles)
    issues: list[str] = []
    for index, first in enumerate(triggers):
        for second in triggers[index + 1:]:
            contexts = {first["context"], second["context"]}
            if len(contexts) > 1 and "global" not in contexts:
                continue
            a, b = str(first["trigger"]).lower(), str(second["trigger"]).lower()
            if a == b:
                issues.append(f"duplicate hotstring trigger {first['trigger']!r}: {first['source']} and {second['source']}")
                continue
            for short, long in ((first, second), (second, first)):
                short_text, long_text = str(short["trigger"]).lower(), str(long["trigger"]).lower()
                if len(long_text) <= len(short_text) or not long_text.startswith(short_text):
                    continue
                if short["immediate"]:
                    issues.append(f"immediate trigger {short['source']} fires before {long['source']} can be typed")
                elif long_text[len(short_text)] in HOTSTRING_END_CHARS:
                    issues.append(f"trigger {short['source']} ends on {long_text[len(short_text)]!r} and competes with {long['source']}")
    return issues


def validate_hotstrings(entries: list[dict[str, object]], profiles: list[dict[str, object]]) -> None:
    issues = find_hotstring_conflicts(entries, profiles)
    if issues:
        raise CatalogError("Hotstring trigger conflicts:\n- " + "\n- ".join(issues))


def catalog_items_sha256(items: object) -> str:
    """Content hash used by ai/catalog-review.json; mirrored in ai/health_check.py."""
    canonical = json.dumps(items, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _load_all() -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    entries = load_db()
    profiles = load_hotstring_profiles()
    validate_hotstrings(entries, profiles)
    return entries, profiles


def _edit_catalog(description: str, apply) -> tuple[list[dict[str, object]], list[dict[str, object]]]:
    """Apply one catalog edit; restore the previous DB bytes if validation fails."""
    backup = DB_PATH.read_bytes()
    try:
        with sqlite3.connect(DB_PATH) as connection:
            apply(connection)
        loaded = _load_all()
    except BaseException:
        DB_PATH.write_bytes(backup)
        raise
    print(f"Catalog updated: {description}")
    return loaded


def _require_profile(connection: sqlite3.Connection, profile_id: str) -> None:
    if not connection.execute("SELECT 1 FROM hotstring_profiles WHERE id = ?", (profile_id,)).fetchone():
        raise CatalogError(f"Unknown hotstring profile: {profile_id}")


def add_hotstring(profile_id: str, trigger: str, value: str, immediate: bool | None):
    def apply(connection: sqlite3.Connection) -> None:
        _require_profile(connection, profile_id)
        if not trigger or not value:
            raise CatalogError("trigger and value are required")
        if connection.execute(
            "SELECT 1 FROM hotstring_entries WHERE profile_id = ? AND trigger = ?", (profile_id, trigger)
        ).fetchone():
            raise CatalogError(f"{profile_id}: trigger already exists: {trigger}")
        next_order = connection.execute(
            "SELECT COALESCE(MAX(sort_order), -1) + 1 FROM hotstring_entries WHERE profile_id = ?", (profile_id,)
        ).fetchone()[0]
        connection.execute(
            "INSERT INTO hotstring_entries (profile_id, sort_order, trigger, value, immediate) VALUES (?, ?, ?, ?, ?)",
            (profile_id, next_order, trigger, value, int(bool(immediate))),
        )
    return _edit_catalog(f"added {profile_id}:{trigger}", apply)


def set_hotstring(profile_id: str, trigger: str, value: str | None, immediate: bool | None):
    if value is None and immediate is None:
        raise CatalogError("--set-hotstring requires --value and/or --immediate/--no-immediate")

    def apply(connection: sqlite3.Connection) -> None:
        _require_profile(connection, profile_id)
        if value is not None:
            if not value:
                raise CatalogError("value must not be empty")
            cursor = connection.execute(
                "UPDATE hotstring_entries SET value = ? WHERE profile_id = ? AND trigger = ?", (value, profile_id, trigger)
            )
        if immediate is not None:
            cursor = connection.execute(
                "UPDATE hotstring_entries SET immediate = ? WHERE profile_id = ? AND trigger = ?",
                (int(immediate), profile_id, trigger),
            )
        if cursor.rowcount != 1:
            raise CatalogError(f"{profile_id}: trigger not found: {trigger}")
    return _edit_catalog(f"updated {profile_id}:{trigger}", apply)


def remove_hotstring(profile_id: str, trigger: str):
    def apply(connection: sqlite3.Connection) -> None:
        _require_profile(connection, profile_id)
        cursor = connection.execute(
            "DELETE FROM hotstring_entries WHERE profile_id = ? AND trigger = ?", (profile_id, trigger)
        )
        if cursor.rowcount != 1:
            raise CatalogError(f"{profile_id}: trigger not found: {trigger}")
    return _edit_catalog(f"removed {profile_id}:{trigger}", apply)


def _hotkey_column_value(field: str, value: object) -> object:
    if field == "platform":
        return value if isinstance(value, str) else json.dumps(value)
    if field in {"sort_order", "active"}:
        try:
            return int(value)  # type: ignore[arg-type]
        except (TypeError, ValueError) as exc:
            raise CatalogError(f"{field} must be an integer") from exc
    return value


def add_hotkey(payload_json: str):
    try:
        payload = json.loads(payload_json)
    except json.JSONDecodeError as exc:
        raise CatalogError(f"--add-hotkey expects a JSON object: {exc}") from exc
    if not isinstance(payload, dict):
        raise CatalogError("--add-hotkey expects a JSON object")
    unknown = set(payload) - set(DB_COLUMNS)
    if unknown:
        raise CatalogError(f"Unknown hotkey fields: {', '.join(sorted(unknown))}")

    def apply(connection: sqlite3.Connection) -> None:
        row = dict(payload)
        row.setdefault("active", 1)
        row.setdefault("portability", "windows-only")
        if "sort_order" not in row:
            row["sort_order"] = connection.execute("SELECT COALESCE(MAX(sort_order), -1) + 1 FROM hotkeys").fetchone()[0]
        columns = [column for column in DB_COLUMNS if column in row]
        connection.execute(
            f"INSERT INTO hotkeys ({', '.join(columns)}) VALUES ({', '.join('?' for _ in columns)})",
            [_hotkey_column_value(column, row[column]) for column in columns],
        )
    return _edit_catalog(f"added hotkey {payload.get('id')}", apply)


def set_hotkey(hotkey_id: str, field: str, value: str):
    if field not in DB_COLUMNS or field == "id":
        raise CatalogError(f"Field cannot be set: {field}. Allowed: {', '.join(c for c in DB_COLUMNS if c != 'id')}")

    def apply(connection: sqlite3.Connection) -> None:
        cursor = connection.execute(
            f"UPDATE hotkeys SET {field} = ? WHERE id = ?", (_hotkey_column_value(field, value), hotkey_id)
        )
        if cursor.rowcount != 1:
            raise CatalogError(f"Unknown hotkey id: {hotkey_id}")
    return _edit_catalog(f"set {hotkey_id}.{field}", apply)


def remove_hotkey(hotkey_id: str):
    def apply(connection: sqlite3.Connection) -> None:
        cursor = connection.execute("DELETE FROM hotkeys WHERE id = ?", (hotkey_id,))
        if cursor.rowcount != 1:
            raise CatalogError(f"Unknown hotkey id: {hotkey_id}")
    return _edit_catalog(f"removed hotkey {hotkey_id}", apply)


def mark_reviewed(profiles: list[dict[str, object]], profile_id: str) -> None:
    profile = next((item for item in profiles if item["id"] == profile_id), None)
    if profile is None:
        raise CatalogError(f"Unknown hotstring profile: {profile_id}")
    items = json.loads(generate_windows_hotstring_profile(profile))["items"]
    review = json.loads(CATALOG_REVIEW_PATH.read_text(encoding="utf-8-sig"))
    catalog = next((item for item in review.get("catalogs", []) if item.get("id") == profile_id), None)
    if catalog is None:
        raise CatalogError(f"{CATALOG_REVIEW_PATH.name} has no entry for {profile_id}")
    catalog["status"] = "verified"
    catalog["last_human_verification"] = date.today().isoformat()
    catalog["content_sha256"] = catalog_items_sha256(items)
    CATALOG_REVIEW_PATH.write_text(json.dumps(review, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Marked {profile_id} as human-reviewed ({catalog['last_human_verification']}).")


def report_review_state(profile_ids: set[str]) -> None:
    for profile_id in sorted(profile_ids):
        print(
            f"Catalog {profile_id} changed: health_check will flag it until the human confirms it; then run "
            f"python ai/hotkey_sync.py --mark-reviewed {profile_id}"
        )


def _ahk_str(value: str) -> str:
    return value.replace("`", "``").replace('"', '`"')


def _format_hotif(entry: dict[str, object]) -> str | None:
    windows_context = str(entry.get("windows_context") or "").strip()
    return f"#hotif {windows_context}" if windows_context else None


def _render_block(entry: dict[str, object]) -> str:
    action = _sap_tcode(entry)
    rendered_action = (
        f'services.sap.runTcode("{_ahk_str(action)}")'
        if action is not None
        else str(entry["action"])
    )
    if entry["type"] == "hotstring":
        lines = [f'{entry["options"]}{entry["trigger"]}::{{', rendered_action, "}"]
    else:
        lines = [f'{entry["key"]}::{{', rendered_action, "}"]
    return "\n".join(lines)


def generate_file(file_key: str, entries: list[dict[str, object]]) -> str:
    active = [
        entry for entry in entries
        if entry["active"] and "windows" in entry["platform"]
    ]
    lines = [GENERATED_MARKER, "; Human source: platforms/shared/data/hotkeys.db", "; Regenerate: python ai/hotkey_sync.py --sync"]
    if file_key in FILE_HEADERS:
        lines.append(FILE_HEADERS[file_key])
    lines.append("")
    if not active:
        lines.append("; No active entries.")
        return "\n".join(lines) + "\n"

    groups: dict[str, list[dict[str, object]]] = {}
    order: list[str] = []
    for entry in active:
        context_key = str(entry.get("windows_context") or "__global__")
        if context_key not in groups:
            groups[context_key] = []
            order.append(context_key)
        groups[context_key].append(entry)

    previous_hotif: str | None = None
    for context_key in order:
        context_entries = groups[context_key]
        hotif = _format_hotif(context_entries[0])
        if hotif != previous_hotif:
            if hotif:
                lines.append(hotif)
            elif previous_hotif is not None:
                lines.append("#hotif")
            previous_hotif = hotif
        lines.extend(_render_block(entry) for entry in context_entries)
    if previous_hotif is not None:
        lines.append("#hotif")
    return "\n".join(lines) + "\n"


def _display_key(entry: dict[str, object]) -> str:
    if entry["type"] == "hotstring":
        return str(entry["trigger"])
    raw = str(entry["key"])
    prefixes: list[str] = []
    while raw and raw[0] in "~$*":
        raw = raw[1:]
    modifiers = (("#", "Win"), ("^", "Ctrl"), ("!", "Alt"), ("+", "Shift"))
    changed = True
    while changed and raw:
        changed = False
        for symbol, name in modifiers:
            if raw.startswith(symbol):
                prefixes.append(name)
                raw = raw[1:]
                changed = True
                break
    names = {
        "xbutton1": "MouseBack", "xbutton2": "MouseFwd", "pgdn": "PageDown",
        "pgup": "PageUp", "esc": "Esc", "enter": "Enter", "`": "Backtick",
        "left": "Left", "right": "Right", "up": "Up", "down": "Down",
    }
    if raw.lower() in names:
        key_name = names[raw.lower()]
    elif re.fullmatch(r"f\d+", raw.lower()) or (len(raw) == 1 and raw.isalpha()):
        key_name = raw.upper()
    else:
        key_name = raw
    return "+".join([*prefixes, key_name])


def generate_readme(entries: list[dict[str, object]]) -> str:
    active = [entry for entry in entries if entry["active"]]
    hotkey_count = sum(entry["type"] == "hotkey" for entry in active)
    hotstring_count = sum(entry["type"] == "hotstring" for entry in active)
    by_file: dict[str, list[dict[str, object]]] = defaultdict(list)
    for entry in active:
        by_file[str(entry["file"])].append(entry)

    lines = [
        "# Keyflow - Hotkey Reference",
        "",
        "> AUTO-GENERATED by `python ai/hotkey_sync.py --sync` from `platforms/shared/data/hotkeys.db`.",
        "> Humans manage the SQLite database; generated AHK and Markdown files must not be edited directly.",
        "",
        f"Active catalog: **{hotkey_count} hotkeys** and **{hotstring_count} hotstrings**.",
    ]
    ordered_files = sorted(by_file, key=lambda name: (FILE_ORDER.get(name, 999), name))
    for file_key in ordered_files:
        lines.extend(["", f"## {FILE_TITLES.get(file_key, file_key)}", "", "| Trigger | Context | Action | Implementation | Portability |", "|---|---|---|---|---|"])
        for entry in by_file[file_key]:
            trigger = _display_key(entry).replace("|", "\\|")
            context = str(entry.get("context_label") or "global").replace("|", "\\|")
            label = str(entry["label"]).replace("|", "\\|")
            platforms = ", ".join(str(value) for value in entry["platform"])
            portability = str(entry["portability"])
            lines.append(f"| `{trigger}` | {context} | {label} | {platforms} | {portability} |")
    return "\n".join(lines) + "\n"


def _lua_str(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def generate_macos_bindings(entries: list[dict[str, object]]) -> str:
    """Emit binding metadata and portable SAP transaction codes for macOS.
    Other behavior remains hand-authored in actions.lua, matched by id."""
    active = [
        entry for entry in entries
        if entry["active"] and "macos" in entry["platform"]
    ]
    lines = [
        LUA_GENERATED_MARKER,
        "-- Human source: platforms/shared/data/hotkeys.db",
        "-- Regenerate: python ai/hotkey_sync.py --sync",
        "-- Behavior lives in platforms/macos/hammerspoon/actions.lua and hotstrings.lua.",
        "-- sap-tcode:<code> actions expose tcode for the shared SAP adapter.",
        "",
        "return {",
    ]
    for entry in sorted(active, key=lambda e: str(e["id"])):
        key_or_trigger = entry["trigger"] if entry["type"] == "hotstring" else entry["key"]
        tcode = _sap_tcode(entry) or ""
        lines.append(
            "  {"
            f'id = "{_lua_str(str(entry["id"]))}", '
            f'type = "{_lua_str(str(entry["type"]))}", '
            f'key = "{_lua_str(str(key_or_trigger))}", '
            f'contextLabel = "{_lua_str(str(entry.get("context_label") or ""))}", '
            f'tcode = "{_lua_str(tcode)}", '
            f'label = "{_lua_str(str(entry["label"]))}"'
            + (f', immediate = {"true" if "*" in str(entry["options"] or "") else "false"}' if entry["type"] == "hotstring" else "")
            # AHK "?" option: fires even right after a letter (inside a word).
            + (', insideWord = true' if entry["type"] == "hotstring" and "?" in str(entry["options"] or "") else "")
            + "},"
        )
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate_windows_hotstring_profile(profile: dict[str, object]) -> str:
    items: list[dict[str, object]] = []
    for entry in profile["entries"]:
        item = {"trigger": entry["trigger"], "value": entry["value"]}
        if entry["immediate"]:
            item["immediate"] = True
        items.append(item)
    payload = {
        "format": "hotstring-items-v1",
        "source": f"shared/hotkeys.db:{profile['id']}",
        "items": items,
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def generate_macos_hotstring_profiles(profiles: list[dict[str, object]]) -> str:
    lines = [
        LUA_GENERATED_MARKER,
        "-- Human source: platforms/shared/data/hotkeys.db",
        "-- Regenerate: python ai/hotkey_sync.py --sync",
        "",
        "return {",
    ]
    for profile in profiles:
        if not profile["active"] or "macos" not in profile["platform"]:
            continue
        lines.append(
            "  {"
            f'id = "{_lua_str(str(profile["id"]))}", '
            f'mode = "{_lua_str(str(profile["mode"]))}", '
            f'contextLabel = "{_lua_str(str(profile["context_label"]))}", '
            "entries = {"
        )
        for entry in profile["entries"]:
            lines.append(
                "    {"
                f'trigger = "{_lua_str(str(entry["trigger"]))}", '
                f'value = "{_lua_str(str(entry["value"]))}", '
                f'immediate = {"true" if entry["immediate"] else "false"}'
                "},"
            )
        lines.append("  }},")
    lines.extend(["}", ""])
    return "\n".join(lines)


def expected_artifacts(
    entries: list[dict[str, object]],
    profiles: list[dict[str, object]],
) -> dict[Path, str]:
    by_file: dict[str, list[dict[str, object]]] = defaultdict(list)
    for entry in entries:
        by_file[str(entry["file"])].append(entry)
    artifacts = {
        HOTKEYS_DIR / f"{file_key}.ahk": generate_file(file_key, file_entries)
        for file_key, file_entries in by_file.items()
    }
    for profile in profiles:
        artifacts[WINDOWS_DATA_DIR / f"{profile['id']}.json"] = generate_windows_hotstring_profile(profile)
    artifacts[README_PATH] = generate_readme(entries)
    artifacts[MACOS_BINDINGS_PATH] = generate_macos_bindings(entries)
    artifacts[MACOS_HOTSTRING_PROFILES_PATH] = generate_macos_hotstring_profiles(profiles)
    return artifacts


def stale_generated_files(expected_paths: set[Path]) -> list[Path]:
    stale: list[Path] = []
    for path in HOTKEYS_DIR.rglob("*.ahk"):
        if path in expected_paths:
            continue
        try:
            first_line = path.read_text(encoding="utf-8-sig").splitlines()[0]
        except (IndexError, OSError):
            continue
        if first_line == GENERATED_MARKER:
            stale.append(path)
    return stale


def sync(entries: list[dict[str, object]], profiles: list[dict[str, object]]) -> None:
    artifacts = expected_artifacts(entries, profiles)
    for path, content in artifacts.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    stale = stale_generated_files(set(artifacts))
    for path in stale:
        path.unlink()
    print(f"Generated {len(artifacts)} artifacts from {len(entries)} catalog entries.")
    if stale:
        print(f"Removed {len(stale)} stale generated files.")


def check(entries: list[dict[str, object]], profiles: list[dict[str, object]]) -> bool:
    artifacts = expected_artifacts(entries, profiles)
    drift: list[str] = []
    for path, expected in artifacts.items():
        actual = path.read_text(encoding="utf-8-sig") if path.exists() else None
        if actual != expected:
            drift.append(path.relative_to(ROOT).as_posix())
    drift.extend(path.relative_to(ROOT).as_posix() for path in stale_generated_files(set(artifacts)))
    if drift:
        print("Generated hotkey artifacts are stale:")
        for path in sorted(drift):
            print(f"  {path}")
        print("Run: python ai/hotkey_sync.py --sync")
        return False
    print(f"Hotkey catalog is valid and {len(artifacts)} generated artifacts are current.")
    return True


def list_entries(entries: list[dict[str, object]], inactive_only: bool = False) -> None:
    rows = [entry for entry in entries if (not entry["active"]) == inactive_only]
    print(f"{'ID':<30} {'FILE':<22} {'KEY/TRIGGER':<18} {'PLATFORM':<12} {'PORTABILITY':<16} LABEL")
    print("-" * 130)
    for entry in rows:
        platforms = ",".join(str(value) for value in entry["platform"])
        print(f"{entry['id']:<30} {entry['file']:<22} {_display_key(entry):<18} {platforms:<12} {entry['portability']:<16} {entry['label']}")
    print(f"\n{len(rows)} entries")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    actions = parser.add_mutually_exclusive_group(required=True)
    actions.add_argument("--init-db", action="store_true", help="Create a new empty SQLite catalog if none exists.")
    actions.add_argument(
        "--migrate-hotkeys-schema",
        action="store_true",
        help="Migrate the legacy hotkeys table to the current reduced schema.",
    )
    actions.add_argument(
        "--migrate-hotstring-profiles",
        action="store_true",
        help="Import the existing Windows hotstring JSON profiles into hotkeys.db once.",
    )
    actions.add_argument("--sync", action="store_true", help="Generate AHK and Markdown artifacts from hotkeys.db.")
    actions.add_argument("--check", action="store_true", help="Validate the catalog and detect generated artifact drift.")
    actions.add_argument("--list", action="store_true", help="List active catalog entries.")
    actions.add_argument("--list-inactive", action="store_true", help="List inactive catalog entries.")
    actions.add_argument("--add-hotstring", nargs=3, metavar=("PROFILE", "TRIGGER", "VALUE"), help="Add a hotstring entry.")
    actions.add_argument("--set-hotstring", nargs=2, metavar=("PROFILE", "TRIGGER"), help="Change a hotstring entry.")
    actions.add_argument("--remove-hotstring", nargs=2, metavar=("PROFILE", "TRIGGER"), help="Remove a hotstring entry.")
    actions.add_argument("--add-hotkey", metavar="JSON", help="Add a hotkeys row from a JSON object of column values.")
    actions.add_argument("--set-hotkey", nargs=3, metavar=("ID", "FIELD", "VALUE"), help="Change one hotkeys column.")
    actions.add_argument("--remove-hotkey", metavar="ID", help="Remove a hotkeys row.")
    actions.add_argument(
        "--mark-reviewed",
        metavar="PROFILE",
        help="Record human review of a hotstring catalog's current content in ai/catalog-review.json.",
    )
    parser.add_argument("--value", help="New value for --set-hotstring.")
    parser.add_argument(
        "--immediate",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Fire without an ending character (replace profiles only).",
    )
    args = parser.parse_args()
    try:
        if args.init_db:
            create_db()
            return 0
        if args.migrate_hotkeys_schema:
            migrate_hotkeys_schema()
            return 0
        if args.migrate_hotstring_profiles:
            migrate_hotstring_profiles()
            return 0
        if args.add_hotstring:
            profile_id, trigger, value = args.add_hotstring
            sync(*add_hotstring(profile_id, trigger, value, args.immediate))
            report_review_state({profile_id})
            return 0
        if args.set_hotstring:
            profile_id, trigger = args.set_hotstring
            sync(*set_hotstring(profile_id, trigger, args.value, args.immediate))
            report_review_state({profile_id})
            return 0
        if args.remove_hotstring:
            profile_id, trigger = args.remove_hotstring
            sync(*remove_hotstring(profile_id, trigger))
            report_review_state({profile_id})
            return 0
        if args.add_hotkey:
            sync(*add_hotkey(args.add_hotkey))
            return 0
        if args.set_hotkey:
            sync(*set_hotkey(*args.set_hotkey))
            return 0
        if args.remove_hotkey:
            sync(*remove_hotkey(args.remove_hotkey))
            return 0
        entries, profiles = _load_all()
        if args.mark_reviewed:
            if not check(entries, profiles):
                raise CatalogError("Generated artifacts are stale; run --sync before --mark-reviewed.")
            mark_reviewed(profiles, args.mark_reviewed)
            return 0
        if args.sync:
            sync(entries, profiles)
            return 0
        if args.check:
            return 0 if check(entries, profiles) else 1
        list_entries(entries, inactive_only=args.list_inactive)
        return 0
    except (CatalogError, sqlite3.Error, OSError) as exc:
        print(f"hotkey_sync: {exc}", file=sys.stderr)
        return 1

if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
